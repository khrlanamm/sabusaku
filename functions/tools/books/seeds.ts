// Curated starting points for the book catalog: authors whose books are
// harvested, and well-known titles that must be looked up one by one.
//
// Sources: Indonesian literary history as taught in SMA (Balai Pustaka,
// Pujangga Baru, Angkatan '45, '66 and later; see id.wikipedia.org
// "Sastra Indonesia" and "Angkatan dalam sastra Indonesia"), winners of the
// Kusala Sastra Khatulistiwa and the DKJ novel competition, bestseller lists
// of Gramedia, Mizan and Bentang, and the Indonesian editions of translated
// books commonly read by teenagers (Gramedia Pustaka Utama, Mizan, Noura,
// KPG, Elex Media). Wikipedia lists (wiki.ts) widen the title list.

export type Category =
  | "Novel"
  | "Sastra Klasik"
  | "Remaja"
  | "Puisi"
  | "Kumpulan Cerpen"
  | "Sejarah"
  | "Biografi"
  | "Agama"
  | "Pengembangan Diri"
  | "Sains"
  | "Bisnis"
  | "Komik"
  | "Anak"
  | "Nonfiksi Umum"
  | "Lainnya";

export interface SeedAuthor {
  name: string;
  aliases?: string[];
  /** Category of most of their books, used when the source gives none. */
  category: Category;
  /** Balai Pustaka to Angkatan '66: fiction becomes "Sastra Klasik". */
  classic?: boolean;
  /** Foreign author: only Indonesian editions are kept. */
  translated?: boolean;
  /** At most this many books from the author (default 25). */
  max?: number;
}

export interface SeedTitle {
  title: string;
  author: string;
  category?: Category;
  /** Original title of a translated book, to help the lookup. */
  original?: string;
}

const a = (name: string, category: Category, extra: Partial<SeedAuthor> = {}): SeedAuthor => ({
  name,
  category,
  ...extra,
});

const classic = (name: string, category: Category = "Sastra Klasik", extra: Partial<SeedAuthor> = {}) =>
  a(name, category, {classic: true, ...extra});

const translated = (name: string, category: Category, extra: Partial<SeedAuthor> = {}) =>
  a(name, category, {translated: true, max: 15, ...extra});

